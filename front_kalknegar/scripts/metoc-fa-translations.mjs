const phraseEntries = Object.entries(PHRASES).sort(
  ([left], [right]) => right.length - left.length,
);

function escaped(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function translateMetocText(value) {
  if (EXACT[value]) return EXACT[value];
  let result = value;
  for (const [english, persian] of phraseEntries) {
    result = result.replace(
      new RegExp(`(^|[^A-Za-z])${escaped(english)}(?=$|[^A-Za-z])`, "gi"),
      (_, prefix) => `${prefix}${persian}`,
    );
  }
  result = result.replace(/[A-Za-z]+/g, (word) => {
    const key = word.toLowerCase();
    if (key === "ifr" || key === "mvfr" || key === "vdr" || key === "miw") {
      return key.toUpperCase();
    }
    return WORDS[key] ?? word;
  });
  return result
    .replace(/\s+/g, " ")
    .replace(/,/g, "،")
    .replace(/\s+([،؛:)])/g, "$1")
    .replace(/([(])\s+/g, "$1")
    .trim();
}
