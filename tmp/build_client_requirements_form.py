def set_cell_shading(cell, fill: str) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), fill)


def set_cell_margins(cell, top=100, start=120, bottom=100, end=120) -> None:
    tc = cell._tc
    tc_pr = tc.get_or_add_tcPr()
    tc_mar = tc_pr.first_child_found_in("w:tcMar")
    if tc_mar is None:
        tc_mar = OxmlElement("w:tcMar")
        tc_pr.append(tc_mar)
    for margin, value in (("top", top), ("start", start), ("bottom", bottom), ("end", end)):
        node = tc_mar.find(qn(f"w:{margin}"))
        if node is None:
            node = OxmlElement(f"w:{margin}")
            tc_mar.append(node)
        node.set(qn("w:w"), str(value))
        node.set(qn("w:type"), "dxa")


def set_cell_width(cell, width_dxa: int) -> None:
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_w = tc_pr.find(qn("w:tcW"))
    if tc_w is None:
        tc_w = OxmlElement("w:tcW")
        tc_pr.append(tc_w)
    tc_w.set(qn("w:w"), str(width_dxa))
    tc_w.set(qn("w:type"), "dxa")


def set_table_geometry(table, widths_dxa: list[int], indent_dxa=120, rtl=True) -> None:
    total = sum(widths_dxa)
    table.autofit = False
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    tbl_pr = table._tbl.tblPr

    tbl_w = tbl_pr.find(qn("w:tblW"))
    if tbl_w is None:
        tbl_w = OxmlElement("w:tblW")
        tbl_pr.append(tbl_w)
    tbl_w.set(qn("w:w"), str(total))
    tbl_w.set(qn("w:type"), "dxa")

    tbl_ind = tbl_pr.find(qn("w:tblInd"))
    if tbl_ind is None:
        tbl_ind = OxmlElement("w:tblInd")
        tbl_pr.append(tbl_ind)
    tbl_ind.set(qn("w:w"), str(indent_dxa))
    tbl_ind.set(qn("w:type"), "dxa")

    layout = tbl_pr.find(qn("w:tblLayout"))
    if layout is None:
        layout = OxmlElement("w:tblLayout")
        tbl_pr.append(layout)
    layout.set(qn("w:type"), "fixed")

    if rtl and tbl_pr.find(qn("w:bidiVisual")) is None:
        bidi = OxmlElement("w:bidiVisual")
        tbl_pr.append(bidi)

    grid = table._tbl.tblGrid
    for child in list(grid):
        grid.remove(child)
    for width in widths_dxa:
        col = OxmlElement("w:gridCol")
        col.set(qn("w:w"), str(width))
        grid.append(col)

    for row in table.rows:
        for idx, cell in enumerate(row.cells):
            set_cell_width(cell, widths_dxa[min(idx, len(widths_dxa) - 1)])
            set_cell_margins(cell)
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER


def set_repeat_table_header(row) -> None:
    tr_pr = row._tr.get_or_add_trPr()
    header = OxmlElement("w:tblHeader")
    header.set(qn("w:val"), "true")
    tr_pr.append(header)


def set_font(run, size=10.5, bold=False, color=TEXT, italic=False) -> None:
    run.font.name = FONT
    run._element.get_or_add_rPr().rFonts.set(qn("w:ascii"), FONT)
    run._element.get_or_add_rPr().rFonts.set(qn("w:hAnsi"), FONT)
    run._element.get_or_add_rPr().rFonts.set(qn("w:cs"), FONT)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    run.font.color.rgb = RGBColor.from_string(color)
    rtl = run._element.get_or_add_rPr().find(qn("w:rtl"))
    if rtl is None:
        rtl = OxmlElement("w:rtl")
        run._element.get_or_add_rPr().append(rtl)


def set_rtl_paragraph(paragraph, align=WD_ALIGN_PARAGRAPH.RIGHT) -> None:
    paragraph.alignment = align
    p_pr = paragraph._p.get_or_add_pPr()
    bidi = p_pr.find(qn("w:bidi"))
    if bidi is None:
        bidi = OxmlElement("w:bidi")
        p_pr.append(bidi)
    bidi.set(qn("w:val"), "1")
    paragraph.paragraph_format.space_before = Pt(0)
    paragraph.paragraph_format.space_after = Pt(5)
    paragraph.paragraph_format.line_spacing = 1.15


def add_text(paragraph, text: str, **kwargs):
    set_rtl_paragraph(paragraph, kwargs.pop("align", WD_ALIGN_PARAGRAPH.RIGHT))
    run = paragraph.add_run(text)
    set_font(run, **kwargs)
    return run


def cell_text(cell, text: str, *, bold=False, size=9, color=TEXT, align=WD_ALIGN_PARAGRAPH.RIGHT):
    cell.text = ""
    p = cell.paragraphs[0]
    add_text(p, text, bold=bold, size=size, color=color, align=align)


def add_heading(doc, text: str, level=1):
    p = doc.add_paragraph()
    set_rtl_paragraph(p)
    sizes = {1: 15, 2: 12.5, 3: 11}
    before = {1: 14, 2: 10, 3: 7}
    after = {1: 7, 2: 5, 3: 4}
    p.paragraph_format.space_before = Pt(before[level])
    p.paragraph_format.space_after = Pt(after[level])
    p.paragraph_format.keep_with_next = True
    r = p.add_run(text)
    set_font(r, size=sizes[level], bold=True, color=BLUE if level < 3 else DARK)
    return p


def add_note(doc, title: str, body: str, fill=PALE_BLUE):
    table = doc.add_table(rows=1, cols=1)
    set_table_geometry(table, [9360])
    set_cell_shading(table.cell(0, 0), fill)
    p = table.cell(0, 0).paragraphs[0]
    r = p.add_run(title + ": ")
    set_font(r, size=9.5, bold=True, color=DARK)
    r = p.add_run(body)
    set_font(r, size=9.5, color=TEXT)
    set_rtl_paragraph(p)
    doc.add_paragraph().paragraph_format.space_after = Pt(1)


def add_field_table(doc, rows: list[tuple[str, str]], widths=(2400, 6960)):
    table = doc.add_table(rows=0, cols=2)
    table.style = "Table Grid"
    for label, value in rows:
        cells = table.add_row().cells
        cell_text(cells[0], label, bold=True, size=9.5, color=DARK)
        set_cell_shading(cells[0], LIGHT_GRAY)
        cell_text(cells[1], value, size=9.5)
    set_table_geometry(table, list(widths))
    return table


def add_status_matrix(doc, headers: list[str], rows: list[list[str]], widths: list[int], font_size=8.3):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Table Grid"
    for idx, h in enumerate(headers):
        cell_text(table.rows[0].cells[idx], h, bold=True, size=8.5, color=WHITE, align=WD_ALIGN_PARAGRAPH.CENTER)
        set_cell_shading(table.rows[0].cells[idx], BLUE)
    set_repeat_table_header(table.rows[0])
    for ridx, values in enumerate(rows):
        cells = table.add_row().cells
        for idx, value in enumerate(values):
            align = WD_ALIGN_PARAGRAPH.CENTER if idx in (0, 2, 3, 4) else WD_ALIGN_PARAGRAPH.RIGHT
            cell_text(cells[idx], value, size=font_size, align=align)
            if ridx % 2:
                set_cell_shading(cells[idx], "F8FAFC")
    set_table_geometry(table, widths)
    return table


def add_response_area(doc, label: str, lines=2):
    p = doc.add_paragraph()
    p.paragraph_format.keep_with_next = True
    add_text(p, label, size=9.5, bold=True, color=DARK)
    for _ in range(lines):
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(8)
        p_pr = p._p.get_or_add_pPr()
        borders = OxmlElement("w:pBdr")
        bottom = OxmlElement("w:bottom")
        bottom.set(qn("w:val"), "single")
        bottom.set(qn("w:sz"), "4")
        bottom.set(qn("w:space"), "2")
        bottom.set(qn("w:color"), MID_GRAY)
        borders.append(bottom)
        p_pr.append(borders)
        set_rtl_paragraph(p)


